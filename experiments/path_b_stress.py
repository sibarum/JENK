"""Path-B stress tests: push SymbolicNeuron until it breaks.

Four failure-mode probes:

  Test 1 - Out-of-class data:  generate Y = W X for random W not in the
           M(s) family. The 1-param model can only express matrices of
           shape [[0, -1], [1, s]], so this MUST have residual loss.
           Quantify how badly the s it picks deviates from "best fit."

  Test 2 - Noise + limited data:  Y = M(s_true) X + N(0, sigma^2).
           Vary N, sigma. Compare TEST loss on held-out clean data.
           The 4-param baseline overfits when N is small; the 1-param
           should win on test loss in that regime.

  Test 3 - Omega recovery via real descent:  data generated by M(omega)
           but the trainable s is a real number. We pick numeric
           "proxies" for omega (10, 1e3, 1e6) and watch the descent.
           Should land on s = proxy and confirm that's the loss-optimal
           real value (matching the symbolic optimum from omega_probe).

  Test 4 - Chain non-identifiability:  Y = M(s_total) X for known s_total.
           Train chain(neuron1, neuron2) where both s1, s2 are learnable.
           The composition product is a 2-param family; many (s1, s2)
           give the same M(s2) M(s1). What does the optimizer pick?

Run from JENK/:
    PYTHONPATH=. conda run -n traction python tmp/path_b_stress.py
"""

from __future__ import annotations

import time

import numpy as np
import sympy as sp

from jenk.symbolic_neuron import SymbolicNeuron


# Common knobs (matched to path_b_synthetic_recovery.py).
LR = 0.05
N_STEPS = 1000
SEED = 42


# ---------------------------------------------------------------------- helpers

def build_loss_grad_fns():
    s = sp.Symbol('s', real=True)
    xa, xb = sp.symbols('xa xb', real=True)
    ta, tb = sp.symbols('ta tb', real=True)
    neuron = SymbolicNeuron.generator(s)
    pred_a, pred_b = neuron.forward(xa, xb)
    loss = (pred_a - ta) ** 2 + (pred_b - tb) ** 2
    grad = sp.diff(loss, s)
    return (sp.lambdify((s, xa, xb, ta, tb), loss, 'numpy'),
            sp.lambdify((s, xa, xb, ta, tb), grad, 'numpy'))


def train_sym(loss_fn, grad_fn, X, Y, *, n_steps=N_STEPS, lr=LR, s_init=0.0):
    s = float(s_init)
    losses = []
    xa, xb, ta, tb = X[:, 0], X[:, 1], Y[:, 0], Y[:, 1]
    for _ in range(n_steps):
        l = float(np.mean(loss_fn(s, xa, xb, ta, tb)))
        g = float(np.mean(grad_fn(s, xa, xb, ta, tb)))
        losses.append(l)
        s = s - lr * g
    return s, losses


def train_linear(X, Y, *, n_steps=N_STEPS, lr=LR, rng=None):
    if rng is None:
        rng = np.random.default_rng(SEED)
    W = rng.normal(size=(2, 2)) * 0.1
    losses = []
    n = X.shape[0]
    for _ in range(n_steps):
        err = X @ W.T - Y
        losses.append(float(np.mean(err ** 2)))
        W = W - lr * (2.0 / n) * err.T @ X
    return W, losses


def mse(pred, target):
    return float(np.mean((pred - target) ** 2))


# ============================================================== TEST 1: out-of-class

def test_out_of_class(loss_fn, grad_fn):
    print('#' * 92)
    print('# TEST 1 - OUT-OF-CLASS DATA: Y = W X for random 2x2 W not in the M(s) family')
    print('#' * 92)
    print()
    print('Theory: the 1-param model can only express M(s) = [[0, -1], [1, s]].')
    print('For random W, expected loss minimized at s* = W[1, 1] (matching the (1, 1) entry).')
    print('Residual loss approx (W[0, 0])^2 + (W[0, 1] + 1)^2 + (W[1, 0] - 1)^2 (deviations from M).')
    print()
    rng = np.random.default_rng(SEED)
    n_trials = 5
    n_samples = 200

    print(f"{'trial':>5}  {'W (true)':<48}  {'sym s*':>9}  {'sym loss':>11}  {'lin loss':>11}")
    print('-' * 96)
    for trial in range(n_trials):
        W_true = rng.normal(size=(2, 2))
        X = rng.normal(size=(n_samples, 2))
        Y = X @ W_true.T

        s_recovered, sym_losses = train_sym(loss_fn, grad_fn, X, Y)
        # Theory prediction: s* = W[1,1]; residual = (W[0,0])^2 + (W[0,1]+1)^2 + (W[1,0]-1)^2
        predicted_s = W_true[1, 1]
        predicted_loss = (W_true[0, 0] ** 2
                          + (W_true[0, 1] + 1) ** 2
                          + (W_true[1, 0] - 1) ** 2)

        rng_b = np.random.default_rng(SEED + 1)
        rng_b.normal(size=(n_samples, 2))  # consume to advance state similarly
        W_recovered, lin_losses = train_linear(X, Y, rng=rng_b)

        flat = ' '.join(f'{v:+.3f}' for v in W_true.ravel())
        print(f"{trial:>5}  [{flat}]  "
              f"{s_recovered:>+9.4f}  {sym_losses[-1]:>11.3e}  {lin_losses[-1]:>11.3e}")
        print(f"       theory: s* = W[1,1] = {predicted_s:+.4f}, residual loss = {predicted_loss:.3e}")
    print()
    print('Conclusion: the 1-param model lands on s = W[1,1] and pays a residual loss equal to')
    print('the off-diagonal mismatch with M(s). The free 2x2 baseline fits perfectly. This is the')
    print('inductive bias being honest about its scope: it cannot represent arbitrary 2x2.')
    print()


# ============================================================== TEST 2: noise + limited data

def test_noise_and_data(loss_fn, grad_fn):
    print('#' * 92)
    print('# TEST 2 - NOISE + LIMITED DATA: where 1-param overfit-resistance should bite')
    print('#' * 92)
    print()
    print('Setup: Y_train = M(s_true=1.3) X_train + N(0, sigma^2);  X_test ~ N(0, I) clean.')
    print('Train both models on the noisy small set; report TEST loss on held-out clean Y.')
    print()
    rng = np.random.default_rng(SEED)
    s_true = 1.3
    M_true = np.array([[0.0, -1.0], [1.0, s_true]])
    n_test = 1000
    X_test = rng.normal(size=(n_test, 2))
    Y_test = X_test @ M_true.T

    sigmas = [0.0, 0.1, 0.5, 1.0]
    sample_sizes = [2, 4, 10, 50]

    print(f"{'sigma':>6}  {'N':>4}  {'sym s*':>9}  {'lin train loss':>14}  "
          f"{'sym TEST':>11}  {'lin TEST':>11}  {'sym/lin':>9}")
    print('-' * 96)
    for sigma in sigmas:
        for n in sample_sizes:
            rng_run = np.random.default_rng(SEED + 100 * int(sigma * 10) + n)
            X_train = rng_run.normal(size=(n, 2))
            noise = rng_run.normal(size=(n, 2)) * sigma
            Y_train = X_train @ M_true.T + noise

            s_rec, sym_losses = train_sym(loss_fn, grad_fn, X_train, Y_train)
            rng_b = np.random.default_rng(SEED + 7)
            W_rec, lin_losses = train_linear(X_train, Y_train, rng=rng_b)

            # Test loss on clean held-out:
            sym_pred = np.column_stack([
                -X_test[:, 1],  # pred_a = -xb
                X_test[:, 0] + s_rec * X_test[:, 1],  # pred_b
            ])
            lin_pred = X_test @ W_rec.T

            sym_test = mse(sym_pred, Y_test)
            lin_test = mse(lin_pred, Y_test)
            ratio = sym_test / lin_test if lin_test > 1e-30 else float('inf')
            print(f"{sigma:>6.2f}  {n:>4d}  {s_rec:>+9.5f}  {lin_losses[-1]:>14.3e}  "
                  f"{sym_test:>11.3e}  {lin_test:>11.3e}  {ratio:>9.3e}")
    print()
    print('Read the table:')
    print('  - sym TEST < lin TEST  =>  1-param wins on generalization (inductive bias helps).')
    print('  - sym TEST > lin TEST  =>  1-param hurts (often when model class is correct anyway).')
    print('  - sym/lin > 1 means sym is worse; < 1 means sym is better.')
    print()


# ============================================================== TEST 3: omega via real descent

def test_omega_via_real_descent(loss_fn, grad_fn):
    print('#' * 92)
    print('# TEST 3 - OMEGA RECOVERY ATTEMPT VIA REAL-VALUED GRADIENT DESCENT')
    print('#' * 92)
    print()
    print('Setup: data generated by M(omega_proxy) for various large numeric proxies.')
    print('Per the omega_probe result, optimal s* = omega_proxy (loss surface is (omega-s)^2).')
    print('Real-valued descent should recover s_proxy. The interesting probe is the convergence')
    print('rate as proxy grows — the loss landscape gets steeper, gradients explode.')
    print()
    rng = np.random.default_rng(SEED)
    n_samples = 200

    proxies = [10.0, 100.0, 1000.0, 1e6]
    print(f"{'proxy':>10}  {'recovered s':>14}  {'|err|':>11}  {'final loss':>12}  "
          f"{'final grad':>12}  {'steps to <1e-6 err':>20}")
    print('-' * 96)
    for proxy in proxies:
        X = rng.normal(size=(n_samples, 2))
        M_proxy = np.array([[0.0, -1.0], [1.0, proxy]])
        Y = X @ M_proxy.T

        # We'll track step-by-step convergence.
        s = 0.0
        xa, xb, ta, tb = X[:, 0], X[:, 1], Y[:, 0], Y[:, 1]
        first_below = None
        last_loss = None
        last_grad = None
        for step in range(N_STEPS):
            l = float(np.mean(loss_fn(s, xa, xb, ta, tb)))
            g = float(np.mean(grad_fn(s, xa, xb, ta, tb)))
            if first_below is None and abs(s - proxy) < 1e-6:
                first_below = step
            last_loss, last_grad = l, g
            s = s - LR * g

        steps_str = str(first_below) if first_below is not None else f">{N_STEPS}"
        print(f"{proxy:>10.0e}  {s:>+14.6e}  {abs(s - proxy):>11.3e}  "
              f"{last_loss:>12.3e}  {last_grad:>+12.3e}  {steps_str:>20}")
    print()
    print('Conclusion: real-valued descent CAN reach arbitrary numeric s, including very large')
    print('proxies for omega. But s_proxy = omega has no finite real value -- so for the actual')
    print('symbolic omega, descent cannot terminate. The "infinite proxy" interpretation diverges.')
    print()


# ============================================================== TEST 4: chain identifiability

def test_chain_identifiability(loss_fn, grad_fn):
    print('#' * 92)
    print('# TEST 4 - CHAIN NON-IDENTIFIABILITY: 2 neurons fitting a single matrix product')
    print('#' * 92)
    print()
    print('Setup: Y = M(s_total = 1.5) X. Train chain(neuron1, neuron2), both s learnable.')
    print('Composition: M(s2) M(s1) is a 2-parameter family. Many (s1, s2) yield the SAME')
    print('product matrix. What does the optimizer settle on?')
    print()

    # Build symbolic 2-neuron chain forward and gradients.
    s1, s2 = sp.symbols('s1 s2', real=True)
    xa, xb = sp.symbols('xa xb', real=True)
    ta, tb = sp.symbols('ta tb', real=True)
    n1 = SymbolicNeuron.generator(s1)
    n2 = SymbolicNeuron.generator(s2)
    mid_a, mid_b = n1.forward(xa, xb)
    out_a, out_b = n2.forward(mid_a, mid_b)
    loss_expr = (out_a - ta) ** 2 + (out_b - tb) ** 2
    g1 = sp.diff(loss_expr, s1)
    g2 = sp.diff(loss_expr, s2)
    loss_chain = sp.lambdify((s1, s2, xa, xb, ta, tb), loss_expr, 'numpy')
    g1_fn = sp.lambdify((s1, s2, xa, xb, ta, tb), g1, 'numpy')
    g2_fn = sp.lambdify((s1, s2, xa, xb, ta, tb), g2, 'numpy')

    s_total = 1.5
    n_samples = 200
    rng = np.random.default_rng(SEED)
    X = rng.normal(size=(n_samples, 2))
    M_total = np.array([[0.0, -1.0], [1.0, s_total]])
    Y = X @ M_total.T

    # Try several initializations to see which equilibrium they reach.
    inits = [(0.0, 0.0), (1.0, 1.0), (0.5, 0.5), (-1.0, 2.0), (3.0, -1.0), (0.0, s_total)]
    print(f"{'init s1, s2':>16}  {'final s1':>11}  {'final s2':>11}  "
          f"{'M(s2) M(s1) [m11]':>20}  {'final loss':>12}")
    print('-' * 96)
    for s1_init, s2_init in inits:
        s1_v, s2_v = float(s1_init), float(s2_init)
        xa_v, xb_v, ta_v, tb_v = X[:, 0], X[:, 1], Y[:, 0], Y[:, 1]
        last_loss = None
        for _ in range(N_STEPS):
            l = float(np.mean(loss_chain(s1_v, s2_v, xa_v, xb_v, ta_v, tb_v)))
            d1 = float(np.mean(g1_fn(s1_v, s2_v, xa_v, xb_v, ta_v, tb_v)))
            d2 = float(np.mean(g2_fn(s1_v, s2_v, xa_v, xb_v, ta_v, tb_v)))
            last_loss = l
            s1_v -= LR * d1
            s2_v -= LR * d2
        # What product matrix does this give?
        M1 = np.array([[0.0, -1.0], [1.0, s1_v]])
        M2 = np.array([[0.0, -1.0], [1.0, s2_v]])
        M_prod = M2 @ M1
        print(f"({s1_init:+.2f}, {s2_init:+.2f})    "
              f"{s1_v:>+11.5f}  {s2_v:>+11.5f}  "
              f"{M_prod[1, 1]:>+20.5f}  {last_loss:>12.3e}")
    print()
    print('Theory: M(s2) M(s1) = [[ -1,    -s2          ],     so the (1,1) entry is')
    print('                       [ s1+s2, s1*s2 - 1    ]]     s1*s2 - 1, and the (0,1) entry is -s2.')
    print('To match M(s_total=1.5) = [[0, -1], [1, 1.5]] we need:')
    print('  (0, 0): -1 = 0       <- FAILURE: this is structurally impossible!')
    print('A 2-neuron generator-only chain CANNOT reproduce a single M(s_total).')
    print('Loss should not go to 0; the optimizer settles at the closest-fit (s1, s2) for the')
    print('best-attainable Frobenius distance.')
    print()


# ----------------------------------------------------------------- driver

def main():
    print('Compiling symbolic gradients...', end=' ')
    t0 = time.perf_counter()
    loss_fn, grad_fn = build_loss_grad_fns()
    print(f'done in {time.perf_counter() - t0:.3f}s\n')

    test_out_of_class(loss_fn, grad_fn)
    test_noise_and_data(loss_fn, grad_fn)
    test_omega_via_real_descent(loss_fn, grad_fn)
    test_chain_identifiability(loss_fn, grad_fn)


if __name__ == '__main__':
    main()
